print("\n" + "=" * 60)
print("[1] 1단계 — 첫 번째 얼굴: 행렬은 표다")
print("=" * 60)
import numpy as np

X = np.array([[175, 70, 25],      # 1행: 학생1 (키, 몸무게, 나이)
              [162, 55, 22],      # 2행: 학생2
              [180, 78, 30]])     # 3행: 학생3

print("행렬 X:\n", X)
print("모양(shape):", X.shape, "→ 3행 3열")
print("X[1, 0] =", X[1, 0], "(2번째 학생의 키)")
print("2번째 행 전체 =", X[1])
print("1번째 열 전체 =", X[:, 0])


#======================================================================
# [2] 1.5단계 — 행렬 = 함수
#     숫자 함수 f(x)=4x 와, 벡터를 받아 벡터를 돌려주는 행렬 A 를 비교합니다.
#======================================================================
print("\n" + "=" * 60)
print("[2] 1.5단계 — 행렬 = 함수")
print("=" * 60)
import numpy as np

# ── 1차원: 숫자를 받아 숫자를 돌려주는 함수 ──
def f(x):
    return 4 * x            # 규칙: 4를 곱한다

print("f(3) =", f(3))       # 숫자 → 숫자
print("f(5) =", f(5))

# ── 행렬: 벡터를 받아 벡터를 돌려주는 함수 ──
A = np.array([[2, 0],
              [0, 3]])      # 규칙: x는 2배, y는 3배

벡터 = np.array([1, 1])
print("A @ 벡터 =", A @ 벡터)   # 벡터 → 벡터

# 규칙(A)은 그대로, 입력만 바꿔 본다
print("A @ [2,1] =", A @ np.array([2, 1]))
print("A @ [0,4] =", A @ np.array([0, 4]))


#======================================================================
# [3] 3단계 — 덧셈과 스칼라곱 (원소별 곱 vs 행렬 곱)
#     A + B, 2A, A * B, A @ B 의 차이를 확인합니다.
#======================================================================
print("\n" + "=" * 60)
print("[3] 3단계 — 덧셈과 스칼라곱 (원소별 곱 vs 행렬 곱)")
print("=" * 60)
import numpy as np

A = np.array([[1, 2], [3, 4]])
B = np.array([[5, 6], [7, 8]])

print("A + B =\n", A + B)
print("2 * A =\n", 2 * A)
print("A * B (원소별 곱) =\n", A * B)
print("A @ B (행렬 곱) =\n", A @ B)


#======================================================================
# [4] 읽는 법 ② — 행렬×벡터의 두 관점
#     행 내적 관점과 열 가중합 관점이 NumPy 결과와 같은지 확인합니다.
#======================================================================
print("\n" + "=" * 60)
print("[4] 읽는 법 ② — 행렬×벡터의 두 관점")
print("=" * 60)
import numpy as np

M = np.array([[2, 0],
              [1, 3]])
v = np.array([1, 2])

# 관점 1 — 행과 벡터의 내적
row_view = np.array([np.dot(M[0], v), np.dot(M[1], v)])

# 관점 2 — 열들의 가중합 (v의 성분이 각 열에 곱해짐)
col_view = v[0] * M[:, 0] + v[1] * M[:, 1]

print("관점 1 (행 내적)   :", row_view)
print("관점 2 (열 가중합) :", col_view)
print("NumPy 결과         :", M @ v)
print("세 결과가 모두 같은가?", np.array_equal(row_view, col_view) and np.array_equal(col_view, M @ v))


#======================================================================
# [5] 6단계 — 왜 AB ≠ BA 인가
#     행렬 곱의 순서를 바꾸고, 회전·전단 변환의 합성 순서에 따라 결과가 달라지는 것을 봅니다.
#======================================================================
print("\n" + "=" * 60)
print("[5] 6단계 — 왜 AB ≠ BA 인가")
print("=" * 60)
import numpy as np

A = np.array([[1, 2], [3, 4]])
B = np.array([[5, 6], [7, 8]])

print("A @ B =\n", A @ B)
print("B @ A =\n", B @ A)
print("두 결과가 같은가?", np.array_equal(A @ B, B @ A))

R = np.array([[0, -1], [1, 0]])      # 90도 회전
S = np.array([[1,  1], [0, 1]])      # 전단(기울이기)
print("\n전단 먼저, 회전 나중 (R @ S) =\n", R @ S)
print("회전 먼저, 전단 나중 (S @ R) =\n", S @ R)


#======================================================================
# [6] 7단계 — 연립방정식·역행렬·전치
#     np.linalg.solve 로 해를 구하고 역행렬·단위행렬·전치를 확인합니다.
#======================================================================
print("\n" + "=" * 60)
print("[6] 7단계 — 연립방정식·역행렬·전치")
print("=" * 60)
import numpy as np

# 연립방정식   2x +  y = 5
#              x + 3y = 10
M = np.array([[2, 1],
              [1, 3]])
b = np.array([5, 10])

sol = np.linalg.solve(M, b)                # Mv = b 를 푸는 함수
print("해 (x, y) =", sol)
print("검산 M @ sol =", M @ sol, "→ b와 같은가?", np.allclose(M @ sol, b))

M_inv = np.linalg.inv(M)                   # 역행렬
print("\n역행렬 M⁻¹ =\n", M_inv)
print("M⁻¹ @ M =\n", np.round(M_inv @ M, 10), "← 단위행렬")
print("\n전치 M.T =\n", M.T)


#======================================================================
# [7] 8단계 — ML에서의 행렬: 순전파와 배치 shape
#     입력 1개와 배치 4개에 가중치 W 를 곱해 shape 변화를 확인합니다.
#======================================================================
print("\n" + "=" * 60)
print("[7] 8단계 — ML에서의 행렬: 순전파와 배치 shape")
print("=" * 60)
import numpy as np

W = np.array([[0.5, 0.2],      # 입력1 → 출력1, 출력2
              [0.3, 0.8],      # 입력2 → 출력1, 출력2
              [0.1, 0.4]])     # 입력3 → 출력1, 출력2

x = np.array([1, 2, 3])                    # 데이터 1개 (3차원)
print("입력 1개 :", x.shape, "@", W.shape, "→", (x @ W).shape)
print("출력      :", x @ W)

X = np.array([[1, 2, 3],                   # 데이터 4개를 한 번에 (배치)
              [2, 0, 1],
              [0, 1, 4],
              [3, 3, 3]])
print("\n배치 4개 :", X.shape, "@", W.shape, "→", (X @ W).shape)
print("출력      :\n", np.round(X @ W, 2))

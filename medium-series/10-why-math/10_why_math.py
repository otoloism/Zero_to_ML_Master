#     ⚠️ 책 본문에서 x = x - 0.1 * df(x) 줄 끝의 ← 이 한 줄이 AI 학습의 전부! 가 주석 기호(#) 없이 들어가 있어 SyntaxError 가 납니다. 여기서는 # ← 로 주석 처리해 실행되게 했습니다.

#======================================================================
# [1] 01-11-B 1단계 — 시그마 Σ를 for 문으로 번역하기
#     Σ(i=1~5) i² = 1+4+9+16+25 = 55 를 결과 그릇 total 과 for 반복문으로 그대로 옮깁니다.
#======================================================================
print("\n" + "=" * 60)
print("[1] 01-11-B 1단계 — 시그마 Σ를 for 문으로 번역하기")
print("=" * 60)
# 수학:  Σ(i=1 to 5) i²  =  1 + 4 + 9 + 16 + 25  =  55

total = 0                       # 결과를 담을 그릇
for i in range(1, 6):          # i = 1,2,3,4,5  ← 아래첨자~위첨자
    total = total + i**2     # 더할 대상 = i의 제곱
print(total)                    # 55


#======================================================================
# [2] 01-11-G 6단계 — SymPy로 원시함수 찾고 미분으로 검산
#     sp.integrate 로 부정적분·정적분을 구하고, sp.diff 로 다시 미분해 원래 함수가 나오는지 확인합니다 (적분 검산 3단계).
#======================================================================
print("\n" + "=" * 60)
print("[2] 01-11-G 6단계 — SymPy로 원시함수 찾고 미분으로 검산")
print("=" * 60)
import sympy as sp

x = sp.symbols('x')              # 기호 변수 x 선언
print(sp.integrate(3*x**2, x))      # 부정적분 → x**3
print(sp.integrate(3*x**2, (x, 1, 4)))  # 정적분 [1,4] → 63
print(sp.diff(x**3, x))            # 검산: 미분하면 3*x**2 ✅

# %% [Block 1] cost_function.py
import numpy as np   # 숫자 배열을 다루는 도구입니다. np 라는 별명이 관례입니다.

# ─────────────────────────────────────────────────────
# 공식:  J = (1/2m) × Σ (h(x) − y)²
# 뜻  :  "예측이 정답에서 얼마나 벗어났는지"를 제곱해서
#        모두 더한 뒤, 데이터 개수의 2배로 나눈 값입니다.
# ─────────────────────────────────────────────────────
def compute_cost(theta0, theta1, x, y):
    # ① 예측하기
    #    직선 공식 h(x) = θ₀ + θ₁·x 에 x를 넣습니다.
    #    x가 배열이면 모든 데이터의 예측이 "한 번에" 계산됩니다.
    #    (for 반복문이 필요 없습니다 — 이것을 '벡터화'라고 부릅니다)
    y_hat = theta0 + theta1 * x

    # ② 오차 구하기 : (예측 − 정답)
    #    양수면 너무 크게 예측한 것, 음수면 너무 작게 예측한 것입니다.
    error = y_hat - y

    # ③ 제곱하기
    #    부호를 없애서 +100과 −100이 서로 상쇄되지 않게 합니다.
    #    덤으로, 큰 오차일수록 훨씬 큰 벌점을 받게 됩니다.
    squared = error ** 2

    # ④ 모두 더한 뒤 2m 으로 나누기
    #    len(x) 가 데이터 개수 m 입니다.
    #    2를 곱해 두는 이유는 나중에 미분할 때 2가 약분되기 때문입니다.
    return squared.sum() / (2 * len(x))

# ── 사용해 보기 ──────────────────────────────────────
x = np.array([0, 1, 2, 3])   # 입력 4개
y = np.array([4, 7, 7, 8])   # 정답 4개

# 같은 데이터에 대해 서로 다른 직선 세 개의 점수를 비교합니다.
print(compute_cost(2.0, 2.0, x, y))
print(compute_cost(4.0, 1.4, x, y))
print(compute_cost(3.5, 1.4, x, y))


